create table if not exists public.comments (
 id bigint generated by default as identity primary key,
 nickname text not null default 'anonymous legend' check(char_length(nickname)<=24),
 message text not null check(char_length(message) between 1 and 500),
 created_at timestamptz not null default now()
);
create table if not exists public.reactions (
 id bigint generated by default as identity primary key,
 album_id text not null default 'jalan-sore' check(char_length(album_id) between 1 and 80),
 photo_index integer not null check(photo_index between 0 and 9999),
 emoji text not null check(emoji in ('😂','❤️','😭','🫡')),
 created_at timestamptz not null default now()
);
alter table public.reactions add column if not exists album_id text not null default 'jalan-sore';
alter table public.comments enable row level security;
alter table public.reactions enable row level security;
drop policy if exists "Anyone can read comments" on public.comments;
create policy "Anyone can read comments" on public.comments for select to anon,authenticated using(true);
drop policy if exists "Anyone can post comments" on public.comments;
create policy "Anyone can post comments" on public.comments for insert to anon,authenticated with check(char_length(message) between 1 and 500 and char_length(nickname)<=24);
drop policy if exists "Anyone can read reactions" on public.reactions;
create policy "Anyone can read reactions" on public.reactions for select to anon,authenticated using(true);
drop policy if exists "Anyone can add reactions" on public.reactions;
create policy "Anyone can add reactions" on public.reactions for insert to anon,authenticated with check(char_length(album_id) between 1 and 80 and photo_index between 0 and 9999 and emoji in ('😂','❤️','😭','🫡'));
grant select, insert on public.comments to anon,authenticated;
grant select, insert on public.reactions to anon,authenticated;
grant usage,select on all sequences in schema public to anon,authenticated;
