create table if not exists public.site_content (
  id integer primary key check (id=1),
  albums jsonb not null default '[]'::jsonb check (jsonb_typeof(albums)='array' and pg_column_size(albums)<1500000),
  updated_at timestamptz not null default now()
);
create or replace function public.maaeeenn_timestamp() returns trigger language plpgsql set search_path = '' as $$
begin new.updated_at = now(); return new; end $$;
drop trigger if exists maaeeenn_touch on public.site_content;
create trigger maaeeenn_touch before update on public.site_content for each row execute function public.maaeeenn_timestamp();
alter table public.site_content enable row level security;
drop policy if exists "Anyone reads episodes" on public.site_content;
create policy "Anyone reads episodes" on public.site_content for select to anon, authenticated using (true);
drop policy if exists "Only admin creates episodes" on public.site_content;
create policy "Only admin creates episodes" on public.site_content for insert to authenticated
with check (exists(select 1 from public.admin_users where user_id=(select auth.uid())));
drop policy if exists "Only admin edits episodes" on public.site_content;
create policy "Only admin edits episodes" on public.site_content for update to authenticated
using (exists(select 1 from public.admin_users where user_id=(select auth.uid())))
with check (exists(select 1 from public.admin_users where user_id=(select auth.uid())));
revoke all on public.site_content from anon, authenticated;
grant select on public.site_content to anon, authenticated;
grant insert, update on public.site_content to authenticated;

